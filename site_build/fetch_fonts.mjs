// One-off: downloads the Latin woff2 files of the site's fonts from Google Fonts into site/fonts/
// and writes site/css/fonts.css. All five families are under the SIL Open Font License.
//   node site_build/fetch_fonts.mjs
import { writeFileSync } from 'node:fs';
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/126.0 Safari/537.36';
const url = 'https://fonts.googleapis.com/css2?family=Geist:wght@400;500;600&family=Geist+Mono:wght@400;500&family=Instrument+Serif:ital@0;1&family=Instrument+Sans:wght@400&family=Inria+Sans:wght@400&display=swap';
const css = await (await fetch(url, { headers: { 'user-agent': UA } })).text();
const blocks = css.split('/* ').slice(1).map(b => ({ subset: b.slice(0, b.indexOf(' */')), body: b.slice(b.indexOf('*/') + 2) })).filter(b => b.subset === 'latin');
let out = '/* Self-hosted Latin subsets (SIL Open Font License). Generated by site_build/fetch_fonts.mjs. */\n';
for (const b of blocks) {
  const fam = /font-family: '([^']+)'/.exec(b.body)[1], style = /font-style: (\w+)/.exec(b.body)[1], weight = /font-weight: ([\d ]+)/.exec(b.body)[1].trim();
  const src = /url\(([^)]+)\)/.exec(b.body)[1];
  const name = (fam + '-' + weight.replace(' ', '_') + (style === 'italic' ? 'i' : '')).replace(/\s+/g, '') + '.woff2';
  const buf = Buffer.from(await (await fetch(src)).arrayBuffer());
  writeFileSync(new URL('../site/fonts/' + name, import.meta.url), buf);
  out += `@font-face { font-family: '${fam}'; font-style: ${style}; font-weight: ${weight}; font-display: swap; src: url(../fonts/${name}) format('woff2'); }\n`;
  console.log(name, buf.length);
}
writeFileSync(new URL('../site/css/fonts.css', import.meta.url), out);
